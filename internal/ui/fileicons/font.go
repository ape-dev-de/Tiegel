// width returns the width of s in units with one unit between letters.
func (f *pixelFont) width(s string) int {
	n := len([]rune(s))
	if n == 0 {
		return 0
	}
	return n*f.w + n - 1
}

// has reports whether every rune of s exists in the font.
func (f *pixelFont) has(s string) bool {
	for _, r := range s {
		if _, ok := f.glyph[r]; !ok {
			return false
		}
	}
	return true
}

// text adds the pixels of s with its top-left corner at (x, y). Runs of
// ink in a row become one rectangle.
func (d *drawer) text(f *pixelFont, s string, x, y float32) {
	for _, r := range s {
		rows := f.glyph[r]
		for j, row := range rows {
			for i := 0; i < len(row); {
				if row[i] != '#' {
					i++
					continue
				}
				k := i
				for k < len(row) && row[k] == '#' {
					k++
				}
				d.rect(x+float32(i), y+float32(j), x+float32(k), y+float32(j+1))
				i = k
			}
		}
		x += float32(f.w + 1)
	}
}

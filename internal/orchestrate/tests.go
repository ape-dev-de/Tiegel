// TestRequest asks a test runner to run test files in a directory.
type TestRequest struct {
	// Dir is the project directory to run in (workspace or base tree).
	Dir string
	// Files are test files relative to Dir ("" = all tests).
	Files []string
	// Coverage asks for line coverage (Clover) when a driver exists.
	Coverage bool
}

// Test statuses.
const (
	TestPassed  = "passed"
	TestFailed  = "failed"
	TestIgnored = "ignored"
)

// TestResult is one executed test.
type TestResult struct {
	// ID is "Ns\Cls::method" (with " with data set …" for data sets).
	ID       string `json:"id"`
	File     string `json:"file,omitempty"`
	Status   string `json:"status"`
	Message  string `json:"message,omitempty"`
	Details  string `json:"details,omitempty"`
	FailFile string `json:"failFile,omitempty"`
	FailLine int    `json:"failLine,omitempty"`
}

// TestReport is the result of a test run.
type TestReport struct {
	Tests []TestResult `json:"tests"`
	// Coverage maps project relative files to statement lines and
	// whether they ran; CoverageNote explains missing coverage.
	Coverage     map[string]map[int]bool `json:"-"`
	CoverageNote string                  `json:"coverageNote,omitempty"`
	// Error explains a run without results (runner missing, fatal error).
	Error  string `json:"error,omitempty"`
	Output string `json:"output,omitempty"`
}

// Failed returns the failed tests.
func (r TestReport) Failed() []TestResult {
	var out []TestResult
	for _, t := range r.Tests {
		if t.Status == TestFailed {
			out = append(out, t)
		}
	}
	return out
}

// Green tells whether tests ran and none failed.
func (r TestReport) Green() bool {
	return r.Error == "" && len(r.Tests) > 0 && len(r.Failed()) == 0
}

// Find returns the results whose ID is id or a data set of it.
func (r TestReport) Find(id string) []TestResult {
	id = strings.TrimPrefix(id, `\`)
	var out []TestResult
	for _, t := range r.Tests {
		tid := strings.TrimPrefix(t.ID, `\`)
		if tid == id || strings.HasPrefix(tid, id+" with data set") || strings.HasSuffix(id, "::"+tid) {
			out = append(out, t)
		}
	}
	return out
}

// TestRunner runs tests (PHPUnit in the project interpreter; fakes in
// tests).
type TestRunner interface {
	Run(ctx context.Context, req TestRequest) (TestReport, error)
}

// Compact renders a failure for a role prompt: test, assertion message,
// the head of the trace.
func (t TestResult) Compact() string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s FAILED", t.ID)
	if t.FailFile != "" {
		fmt.Fprintf(&b, " at %s:%d", t.FailFile, t.FailLine)
	}
	if m := strings.TrimSpace(t.Message); m != "" {
		b.WriteString(": " + shorten(oneLine(m), 400))
	}
	if d := strings.TrimSpace(t.Details); d != "" {
		lines := strings.Split(d, "\n")
		if len(lines) > 4 {
			lines = lines[:4]
		}
		b.WriteString("\n    " + strings.Join(lines, "\n    "))
	}
	return b.String()
}

// WorktreeBootstrap returns a PHPUnit bootstrap that runs the tests of a
// worktree with the dependencies of the main checkout: vendor/ is not
// versioned and so missing in the worktree. It loads the main checkout's
// Composer autoloader (relative path vendorRel, from the worktree's PHP
// root) and points the project's own PSR-4 namespaces (autoload and
// autoload-dev of composerJSON) to the worktree, so the code under test
// is the worktree's. orig is the configuration's own bootstrap (worktree
// relative; "" or the vendor autoloader = none). Only relative paths are
// used, so the file works inside a container that mounts the project.
func WorktreeBootstrap(vendorRel string, composerJSON []byte, orig string) (string, error) {
	var cj struct {
		Autoload struct {
			PSR4 map[string]any `json:"psr-4"`
		} `json:"autoload"`
		AutoloadDev struct {
			PSR4 map[string]any `json:"psr-4"`
		} `json:"autoload-dev"`
	}
	if len(composerJSON) > 0 {
		if err := json.Unmarshal(composerJSON, &cj); err != nil {
			return "", fmt.Errorf("orchestrate: composer.json: %w", err)
		}
	}
	psr := map[string][]string{}
	for _, m := range []map[string]any{cj.Autoload.PSR4, cj.AutoloadDev.PSR4} {
		for prefix, v := range m {
			switch d := v.(type) {
			case string:
				psr[prefix] = append(psr[prefix], d)
			case []any:
				for _, x := range d {
					if s, ok := x.(string); ok {
						psr[prefix] = append(psr[prefix], s)
					}
				}
			}
		}
	}
	prefixes := make([]string, 0, len(psr))
	for p := range psr {
		prefixes = append(prefixes, p)
	}
	sort.Strings(prefixes)
	var b strings.Builder
	b.WriteString("<?php\n// Generated by Tiegel plan mode: the dependencies of the main checkout, the project code of this worktree.\n")
	fmt.Fprintf(&b, "$loader = require __DIR__ . %s;\n", phpString("/"+filepath.ToSlash(filepath.Join(vendorRel, "autoload.php"))))
	for _, p := range prefixes {
		var dirs []string
		for _, d := range psr[p] {
			dirs = append(dirs, "__DIR__ . "+phpString("/"+strings.TrimPrefix(filepath.ToSlash(d), "./")))
		}
		fmt.Fprintf(&b, "$loader->setPsr4(%s, [%s]);\n", phpString(p), strings.Join(dirs, ", "))
	}
	if o := filepath.ToSlash(orig); o != "" && !strings.HasSuffix(o, "vendor/autoload.php") {
		fmt.Fprintf(&b, "require __DIR__ . %s;\n", phpString("/"+strings.TrimPrefix(o, "./")))
	}
	return b.String(), nil
}

func phpString(s string) string {
	return "'" + strings.NewReplacer(`\`, `\\`, `'`, `\'`).Replace(s) + "'"
}
